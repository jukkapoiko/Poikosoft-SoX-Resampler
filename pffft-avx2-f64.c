/* Read a virtual ordered spectrum of length N generated by inserting a
 * zero between N/2 time samples. The first half contains the original
 * N/2-bin real spectrum in ordered PFFFT form. The second half is its
 * conjugate mirror. All four-lane loads preserve the exact bit patterns. */
static inline v4sf soxr_l2_load(double const * half, int N, int vec) {
  int i = vec * 4;
  if(i == 0)
    return _mm256_setr_pd(half[0], half[0], half[2], half[3]);
  if(i == N / 2)
    return _mm256_setr_pd(half[1], 0.0, half[N / 2 - 2], -half[N / 2 - 1]);
  if(i < N / 2)
    return _mm256_load_pd(half + i);
  {
    /* The mirror starts two doubles before a four-double boundary. */
    v4sf x = _mm256_loadu_pd(half + N - i - 2);
    v4sf reversed = _mm256_permute4x64_pd(x, 0x4e);
    v4sf negative_odd = _mm256_castsi256_pd(_mm256_setr_epi64x(0,
         INT64_MIN, 0, INT64_MIN));
    return _mm256_xor_pd(reversed, negative_odd);
  }
}

/* Multiplication follows the existing VCPLXMUL operations exactly.
 * The ordered-half spectrum is translated to SIMD order and multiplied
 * in one streaming pass, omitting a full read/write of a second FFT array. */
static inline void soxr_l2_store_mul(v4sf * out, v4sf const * coef,
    v4sf ar, v4sf ai) {
  v4sf br = coef[0], bi = coef[1];
  VCPLXMUL(ar, ai, br, bi);
  out[0] = ar;
  out[1] = ai;
}

/* Specialized version of unreversed_copy that streams the virtual full
 * spectrum rather than materializing an entire duplicated ordered buffer. */
static inline void soxr_l2_unreversed_copy_fused(int dk, double const * half, int N,
    int first_vec, v4sf * out, int out_stride, v4sf const * coef) {
  v4sf g0, g1, h0, h1;
  int k, vec = first_vec;
  g0 = g1 = soxr_l2_load(half, N, vec++);
  for(k = 1; k < dk; ++k) {
    h0 = soxr_l2_load(half, N, vec++);
    h1 = soxr_l2_load(half, N, vec++);
    g1 = VSWAPHL(g1, h0);
    h0 = VSWAPHL(h0, h1);
    v4sf ar, ai;
    UNINTERLEAVE2(h0, g1, ar, ai);
    soxr_l2_store_mul(out, coef, ar, ai);
    out += out_stride;
    coef += out_stride;
    g1 = h1;
  }
  h0 = soxr_l2_load(half, N, vec++);
  h1 = g0;
  g1 = VSWAPHL(g1, h0);
  h0 = VSWAPHL(h0, h1);
  v4sf ar, ai;
  UNINTERLEAVE2(h0, g1, ar, ai);
  soxr_l2_store_mul(out, coef, ar, ai);
}

static void reorder_l2_fused(int N, void * setup, void * half_buf, void * scratch, void const * coefficients) {
  v4sf const * coef = (v4sf const *) coefficients;
  double const * half = (double const *) half_buf;
  v4sf * out = (v4sf *) ((double *) scratch + N);
  int k, dk = N / 32;
  (void) setup;
  for(k = 0; k < dk; ++k) {
    v4sf a = soxr_l2_load(half, N, 2 * k);
    v4sf b = soxr_l2_load(half, N, 2 * k + 1);
    v4sf ar, ai;
    UNINTERLEAVE2(a, b, ar, ai);
    soxr_l2_store_mul(out + k * 8, coef + k * 8, ar, ai);
    a = soxr_l2_load(half, N, 2 * (2 * dk + k));
    b = soxr_l2_load(half, N, 2 * (2 * dk + k) + 1);
    UNINTERLEAVE2(a, b, ar, ai);
    soxr_l2_store_mul(out + k * 8 + 4, coef + k * 8 + 4, ar, ai);
  }
  soxr_l2_unreversed_copy_fused(dk, half, N, N / 16,
      out + N / 4 - 6, -8, coef + N / 4 - 6);
  soxr_l2_unreversed_copy_fused(dk, half, N, 3 * N / 16,
      out + N / 4 - 2, -8, coef + N / 4 - 2);
  /* PFFFT_REAL overrides DC and Nyquist after the SIMD complex multiply.
   * Both are copied from the zero-inserted input DC value (half[0]). */
  ((double *) out)[0] = half[0] * ((double const *) coef)[0];
  ((double *) out)[4] = half[0] * ((double const *) coef)[4];
}

